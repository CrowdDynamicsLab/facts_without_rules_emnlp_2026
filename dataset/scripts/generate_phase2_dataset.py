def build_phase2_dataset() -> dict:
    seed = build_dataset()
    scenarios = seed["scenarios"] + phase2_scenarios()
    for scenario_record in scenarios:
        scenario_record["handoff_conditions"] = PHASE2_HANDOFF_CONDITIONS
    return {
        "metadata": {
            "dataset_name": "BOUND-Handoff Phase 2 pilot",
            "version": "0.2",
            "description": "Expanded pilot scenarios for summary-collapse experiments and evaluator calibration.",
            "num_scenarios": len(scenarios),
            "phase": "phase2_pilot",
            "inherits_seed_version": seed["metadata"]["version"],
        },
        "handoff_conditions": PHASE2_HANDOFF_CONDITIONS,
        "scenarios": scenarios,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="data/bound_handoff_phase2.json")
    args = parser.parse_args()

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    data = build_phase2_dataset()
    output.write_text(json.dumps(data, indent=2) + "\n")
    print("Wrote {} scenarios to {}".format(len(data["scenarios"]), output))


if __name__ == "__main__":
    main()
